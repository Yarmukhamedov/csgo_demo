"use client";

import React, { useState, useEffect, useRef } from "react";
import { HighlightMoment, MatchData, ReelSettings, PlayerStats } from "@/types/demo";
import { 
  Play, Pause, RotateCcw, Download, Send, 
  FileCode, Sparkles, Volume2, VolumeX, CheckCircle, 
  Flame, Crosshair, Star, Shield
} from "lucide-react";
import confetti from "canvas-confetti";
import { generateHighlightVideo } from "@/lib/video-recorder";
import { TelegramModal } from "./TelegramModal";

interface VideoReelPlayerProps {
  match: MatchData;
  highlights: HighlightMoment[];
  settings: ReelSettings;
  playerStats?: PlayerStats;
}

export const VideoReelPlayer: React.FC<VideoReelPlayerProps> = ({
  match,
  highlights,
  settings,
  playerStats,
}) => {
  const [isPlaying, setIsPlaying] = useState(false);
  const [currentClipIndex, setCurrentClipIndex] = useState(0);
  const [currentKillIndex, setCurrentKillIndex] = useState(0);
  const [isIntroPhase, setIsIntroPhase] = useState(settings.showIntroCard);
  const [progress, setProgress] = useState(0);
  const [isMuted, setIsMuted] = useState(false);
  const [isExporting, setIsExporting] = useState(false);
  const [exportProgress, setExportProgress] = useState(0);
  const [exportSuccess, setExportSuccess] = useState(false);
  const [isTelegramModalOpen, setIsTelegramModalOpen] = useState(false);

  const activeClip = highlights[currentClipIndex];
  const timerRef = useRef<NodeJS.Timeout | null>(null);

  // Playback timer loop
  useEffect(() => {
    if (!isPlaying || highlights.length === 0) {
      if (timerRef.current) clearInterval(timerRef.current);
      return;
    }

    timerRef.current = setInterval(() => {
      setProgress((prev) => {
        if (prev >= 100) {
          // Move to next clip or loop
          if (currentClipIndex < highlights.length - 1) {
            setCurrentClipIndex((idx) => idx + 1);
            setCurrentKillIndex(0);
            return 0;
          } else {
            // Loop back
            setCurrentClipIndex(0);
            setCurrentKillIndex(0);
            setIsIntroPhase(settings.showIntroCard);
            return 0;
          }
        }
        return prev + 2.5;
      });
    }, 150);

    return () => {
      if (timerRef.current) clearInterval(timerRef.current);
    };
  }, [isPlaying, currentClipIndex, highlights.length, settings.showIntroCard]);

  // Advance killfeed during playback
  useEffect(() => {
    if (activeClip && activeClip.kills.length > 0) {
      const killStep = 100 / activeClip.kills.length;
      const targetKillIndex = Math.min(
        activeClip.kills.length - 1,
        Math.floor(progress / killStep)
      );
      setCurrentKillIndex(targetKillIndex);
    }
  }, [progress, activeClip]);

  const handlePlayToggle = () => {
    setIsPlaying(!isPlaying);
  };

  const handleRestart = () => {
    setProgress(0);
    setCurrentClipIndex(0);
    setCurrentKillIndex(0);
    setIsIntroPhase(settings.showIntroCard);
    setIsPlaying(true);
  };

  // Real Video Export using HTML5 Canvas & MediaRecorder
  const handleExportMp4 = async () => {
    if (highlights.length === 0) return;
    setIsExporting(true);
    setExportProgress(5);
    setExportSuccess(false);

    try {
      const videoBlob = await generateHighlightVideo({
        highlights,
        player: playerStats,
        settings,
        mapName: match.mapDisplay,
        onProgress: (percent) => setExportProgress(percent),
      });

      // Create download link for the real generated video file
      const url = URL.createObjectURL(videoBlob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `csdemo_${settings.selectedPlayer.toLowerCase()}_${match.mapDisplay.toLowerCase()}_highlight.webm`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);

      setIsExporting(false);
      setExportSuccess(true);
      confetti({
        particleCount: 140,
        spread: 75,
        origin: { y: 0.6 },
        colors: ["#f59e0b", "#00d2ff", "#ffffff"],
      });
    } catch (err: any) {
      console.error("Video export error:", err);
      setIsExporting(false);
      alert("Rolik renderlashda xatolik: " + (err.message || "Brauzeringiz MediaRecorder'ni qo'llab-quvvatlamaydi"));
    }
  };

  // Generate HLAE .cfg script for local 120 FPS high-res rendering
  const handleDownloadHlaeScript = () => {
    if (!activeClip) return;
    const cfgContent = `// CS2 HLAE Automation Script generated by csdemo.uz
// Match: ${match.id} | Map: ${match.mapName}
// Player: ${settings.selectedPlayer}

echo "=== Loading CS2 Highlight Script ==="
mirv_streams add normal myStream
mirv_streams edit myStream record 1
mirv_streams edit myStream afxFrame 60
mirv_streams edit myStream drawHud 0

// Fast forward to highlight start tick
demo_gototick ${activeClip.tickStart - 128}
echo "Starting render for ${activeClip.title}..."
mirv_cmd at ${activeClip.tickStart} "mirv_streams record start"
mirv_cmd at ${activeClip.tickEnd} "mirv_streams record end; echo Highlight Complete!"
`;

    const blob = new Blob([cfgContent], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `csdemo_highlight_${settings.selectedPlayer}.cfg`;
    a.click();
    URL.revokeObjectURL(url);
  };

  if (highlights.length === 0) {
    return (
      <div className="rounded-2xl bg-[#0c101d] border border-slate-800 p-8 text-center">
        <Crosshair className="w-12 h-12 text-slate-600 mx-auto mb-3" />
        <h3 className="text-base font-bold text-white mb-1">
          Hech qanday highlight tanlanmadi
        </h3>
        <p className="text-xs text-slate-400">
          Rolik yaratish uchun chap tomondagi ro&apos;yxatdan kamida bitta highlightni belgilang.
        </p>
      </div>
    );
  }

  const isVertical = settings.aspectRatio === "9:16";

  return (
    <div className="rounded-2xl bg-[#0c101d] border border-slate-800 p-5 shadow-2xl space-y-5">
      {/* Title & Status */}
      <div className="flex items-center justify-between text-xs">
        <div className="flex items-center gap-2">
          <span className="w-2.5 h-2.5 rounded-full bg-emerald-400 animate-pulse" />
          <span className="font-bold text-white uppercase tracking-wider">
            Jonli Rolik Prevyusi
          </span>
          <span className="text-[10px] text-amber-400 font-mono px-2 py-0.5 rounded bg-amber-500/10 border border-amber-500/20">
            {settings.aspectRatio}
          </span>
        </div>

        <div className="text-slate-400 font-mono text-[11px]">
          Klip {currentClipIndex + 1} / {highlights.length}
        </div>
      </div>

      {/* Screen Container (9:16 vertical phone bezel or 16:9 monitor) */}
      <div className="flex justify-center">
        <div
          className={`relative overflow-hidden rounded-2xl bg-black border-2 border-slate-800 shadow-2xl transition-all ${
            isVertical
              ? "w-[280px] sm:w-[310px] h-[500px] sm:h-[540px]"
              : "w-full aspect-video h-[320px]"
          }`}
        >
          {/* Simulated CS2 In-Game Footage Background */}
          <div className="absolute inset-0 bg-gradient-to-b from-[#10141f] via-[#090d15] to-[#121620] overflow-hidden">
            {/* Cyber grid / tactical lines */}
            <div className="absolute inset-0 cs-grid-bg opacity-30" />
            <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-64 h-64 bg-amber-500/10 rounded-full blur-3xl pointer-events-none" />

            {/* Map label watermark */}
            <div className="absolute top-4 left-4 z-10 flex items-center gap-2">
              <span className="text-[10px] font-black uppercase tracking-widest px-2 py-0.5 rounded bg-black/60 text-slate-300 border border-slate-700 backdrop-blur-md">
                {match.mapDisplay} • CS2
              </span>
            </div>

            {/* Sound toggle button */}
            <button
              onClick={() => setIsMuted(!isMuted)}
              className="absolute top-4 right-4 z-20 p-1.5 rounded-lg bg-black/60 text-slate-300 border border-slate-700 hover:text-white backdrop-blur-md"
            >
              {isMuted ? <VolumeX className="w-3.5 h-3.5" /> : <Volume2 className="w-3.5 h-3.5 text-amber-400" />}
            </button>

            {/* Center Crosshair Mockup */}
            <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 pointer-events-none opacity-80">
              <div className="w-4 h-4 relative">
                <div className="absolute top-1/2 -left-3 -right-3 h-[2px] bg-emerald-400/80 -translate-y-1/2" />
                <div className="absolute left-1/2 -top-3 -bottom-3 w-[2px] bg-emerald-400/80 -translate-x-1/2" />
                <div className="w-1.5 h-1.5 rounded-full bg-emerald-400 absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 shadow-sm shadow-emerald-400" />
              </div>
            </div>

            {/* Player Intro Card Overlay (if enabled) */}
            {settings.showIntroCard && progress < 25 && playerStats && (
              <div className="absolute inset-0 bg-black/80 backdrop-blur-sm z-30 flex flex-col items-center justify-center p-6 text-center animate-fade-in">
                <div className="relative mb-3">
                  <div className="w-16 h-16 rounded-2xl bg-amber-500/20 border-2 border-amber-400 flex items-center justify-center text-xl font-black text-amber-300 shadow-xl shadow-amber-500/30">
                    {playerStats.name.slice(0, 2).toUpperCase()}
                  </div>
                  <span className="absolute -bottom-1 -right-1 px-1.5 py-0.2 rounded bg-amber-500 text-black text-[9px] font-black">
                    LVL {playerStats.faceitLevel || 10}
                  </span>
                </div>

                <h3 className="text-lg font-black text-white tracking-wide">
                  {playerStats.name}
                </h3>
                <p className="text-xs text-amber-400 font-mono mt-0.5">
                  {playerStats.premierRating?.toLocaleString()} CS-Rating
                </p>

                <div className="grid grid-cols-3 gap-2 w-full max-w-[220px] mt-4 pt-4 border-t border-slate-800 text-center">
                  <div>
                    <div className="text-[10px] text-slate-400">K/D</div>
                    <div className="text-xs font-black text-emerald-400 font-mono">
                      {(playerStats.kills / Math.max(1, playerStats.deaths)).toFixed(2)}
                    </div>
                  </div>
                  <div>
                    <div className="text-[10px] text-slate-400">ADR</div>
                    <div className="text-xs font-black text-white font-mono">
                      {playerStats.adr.toFixed(0)}
                    </div>
                  </div>
                  <div>
                    <div className="text-[10px] text-slate-400">HS %</div>
                    <div className="text-xs font-black text-amber-400 font-mono">
                      {playerStats.hsPercentage}%
                    </div>
                  </div>
                </div>
              </div>
            )}

            {/* Killfeed Animation in Top-Right / Center */}
            <div className="absolute top-14 right-3 left-3 z-20 space-y-1.5 pointer-events-none">
              {activeClip.kills.slice(0, currentKillIndex + 1).map((k, idx) => (
                <div
                  key={idx}
                  className="animate-killfeed flex items-center justify-end gap-2 px-3 py-1.5 rounded-lg bg-black/85 border border-amber-500/40 text-xs shadow-lg backdrop-blur-md"
                >
                  <span className="font-black text-amber-400 text-[11px]">
                    {activeClip.killerName}
                  </span>
                  <span className="text-[10px] px-1.5 py-0.5 rounded bg-slate-800 text-slate-200 font-mono">
                    {k.weapon}
                  </span>
                  {k.isHeadshot && (
                    <span className="text-rose-400 text-[10px] font-black tracking-wider">
                      ⚡ HS
                    </span>
                  )}
                  {k.isNoScope && (
                    <span className="text-purple-400 text-[10px] font-bold">
                      NOSCOPE
                    </span>
                  )}
                  <span className="text-slate-500 text-[11px]">→</span>
                  <span className="text-slate-300 font-semibold text-[11px]">
                    {k.victimName}
                  </span>
                </div>
              ))}
            </div>

            {/* Bottom HUD: Highlight Title, Round info, Beat Visualizer */}
            <div className="absolute bottom-4 left-4 right-4 z-20 space-y-2 pointer-events-none">
              {/* Highlight Badge */}
              <div className="flex items-center gap-2">
                <span className="px-2 py-0.5 rounded-md bg-amber-500 text-black text-[10px] font-black uppercase tracking-wider">
                  {activeClip.type}
                </span>
                <span className="text-xs font-bold text-white drop-shadow">
                  Raund {activeClip.roundNumber} ({activeClip.timeFormatted})
                </span>
              </div>

              {/* Title description */}
              <p className="text-xs font-semibold text-slate-200 line-clamp-1 drop-shadow">
                {activeClip.title}
              </p>

              {/* Audio Beat Visualizer bars */}
              {isPlaying && !isMuted && (
                <div className="flex items-center gap-1 h-3 pt-1">
                  {[40, 80, 60, 100, 70, 90, 50, 85, 95, 60].map((h, i) => (
                    <div
                      key={i}
                      className="w-1 bg-amber-400 rounded-full animate-pulse"
                      style={{ height: `${(h * (progress % 50)) / 40 + 2}px` }}
                    />
                  ))}
                  <span className="text-[9px] text-amber-400/80 font-mono ml-2">
                    {settings.musicTrack}
                  </span>
                </div>
              )}
            </div>

            {/* Play/Pause overlay button when hovered */}
            <div
              onClick={handlePlayToggle}
              className="absolute inset-0 flex items-center justify-center cursor-pointer group bg-black/20 hover:bg-black/40 transition-colors"
            >
              {!isPlaying && (
                <div className="w-14 h-14 rounded-full bg-amber-500 text-black flex items-center justify-center shadow-xl shadow-amber-500/40 group-hover:scale-110 transition-transform">
                  <Play className="w-7 h-7 fill-black ml-1" />
                </div>
              )}
            </div>
          </div>

          {/* Timeline progress bar at bottom of player */}
          <div className="absolute bottom-0 left-0 right-0 h-1.5 bg-slate-900 z-30">
            <div
              className="h-full bg-gradient-to-r from-amber-500 to-amber-300 transition-all duration-100"
              style={{ width: `${progress}%` }}
            />
          </div>
        </div>
      </div>

      {/* Playback Controls Bar */}
      <div className="flex items-center justify-between gap-3 pt-1">
        <div className="flex items-center gap-2">
          <button
            onClick={handlePlayToggle}
            className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-xs font-bold text-white transition-all"
          >
            {isPlaying ? (
              <>
                <Pause className="w-3.5 h-3.5" /> To&apos;xtatish
              </>
            ) : (
              <>
                <Play className="w-3.5 h-3.5 fill-white" /> Ijro Qilish
              </>
            )}
          </button>

          <button
            onClick={handleRestart}
            className="p-2 rounded-xl bg-slate-900 hover:bg-slate-800 text-slate-300 hover:text-white transition-all border border-slate-800"
            title="Qayta boshlash"
          >
            <RotateCcw className="w-4 h-4" />
          </button>
        </div>

        <div className="text-right">
          <div className="text-[11px] text-slate-400 font-mono">
            {highlights.length} ta klip • ~{highlights.length * 12} sek
          </div>
        </div>
      </div>

      {/* Export Progress Bar (if rendering) */}
      {isExporting && (
        <div className="space-y-2 p-3.5 rounded-xl bg-amber-500/10 border border-amber-500/30 animate-pulse">
          <div className="flex items-center justify-between text-xs font-bold text-amber-300">
            <span className="flex items-center gap-1.5">
              <Sparkles className="w-3.5 h-3.5" /> Rolik Render Qilinmoqda (1080p MP4)...
            </span>
            <span>{exportProgress}%</span>
          </div>
          <div className="h-2 rounded-full bg-slate-800 overflow-hidden">
            <div
              className="h-full bg-gradient-to-r from-amber-500 to-amber-300 transition-all duration-200"
              style={{ width: `${exportProgress}%` }}
            />
          </div>
        </div>
      )}

      {/* Export Success Banner */}
      {exportSuccess && (
        <div className="flex items-center justify-between p-3.5 rounded-xl bg-emerald-500/10 border border-emerald-500/30 text-emerald-400 text-xs font-bold">
          <div className="flex items-center gap-2">
            <CheckCircle className="w-4 h-4 text-emerald-400" />
            <span>Rolik muvaffaqiyatli tayyorlandi! (MP4 1080p)</span>
          </div>
          <button
            onClick={() => setExportSuccess(false)}
            className="text-slate-400 hover:text-white"
          >
            ✕
          </button>
        </div>
      )}

      {/* Main Export Action Buttons */}
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5 pt-2">
        <button
          onClick={handleExportMp4}
          disabled={isExporting}
          className="w-full py-3 px-4 rounded-xl bg-gradient-to-r from-amber-500 to-amber-600 text-black font-black text-xs hover:brightness-110 active:scale-[0.99] transition-all flex items-center justify-center gap-2 shadow-lg shadow-amber-500/20 disabled:opacity-50"
        >
          <Download className="w-4 h-4" />
          <span>MP4 Rolikni Yuklab Olish</span>
        </button>

        <button
          onClick={() => setIsTelegramModalOpen(true)}
          className="w-full py-3 px-4 rounded-xl bg-sky-500/15 hover:bg-sky-500/25 border border-sky-500/30 text-sky-400 font-bold text-xs transition-all flex items-center justify-center gap-2 text-center"
        >
          <Send className="w-4 h-4" />
          <span>Telegramga Yuborish</span>
        </button>
      </div>

      {/* Secondary HLAE 120 FPS Script Action */}
      <div className="pt-1 border-t border-slate-800/80">
        <button
          onClick={handleDownloadHlaeScript}
          className="w-full py-2 px-3 rounded-xl bg-slate-900 hover:bg-slate-800 border border-slate-800 text-slate-400 hover:text-slate-200 text-[11px] font-semibold flex items-center justify-center gap-2 transition-all"
        >
          <FileCode className="w-3.5 h-3.5 text-amber-400" />
          <span>CS2 HLAE 120 FPS Render Skripti (.cfg)</span>
        </button>
      </div>

      {/* Telegram Share Modal */}
      <TelegramModal
        isOpen={isTelegramModalOpen}
        onClose={() => setIsTelegramModalOpen(false)}
        match={match}
        highlight={activeClip}
      />
    </div>
  );
};
